#!/usr/bin/env bash
# Asserts sole-committer identity and zero commit-message trailers.
#
# Usage:
#   scripts/audit_identity.sh                  # audit git config + full history (all refs)
#   scripts/audit_identity.sh --msg-file FILE  # additionally audit a pending message
#   scripts/audit_identity.sh --history-only --rev HEAD
#       CI mode: skip the local git config (a runner never commits) and audit
#       exactly the history reachable from the commit under test. Any author,
#       committer or trailer that is not the sole identity fails the run.

# Re-exec under real bash when launched via `sh` (POSIX mode lacks process substitution).
if [ -z "${BASH_VERSION:-}" ] || shopt -qo posix 2>/dev/null; then exec bash "$0" "$@"; fi
set -euo pipefail

readonly EXPECTED_NAME="mikeZ98"
readonly EXPECTED_EMAIL="145975972+mikeZ98@users.noreply.github.com"
# Case-insensitive markers of AI attribution or any git trailer we forbid.
readonly FORBIDDEN_RE='co-authored-by|signed-off-by|generated with|generated by|anthropic|claude|copilot|chatgpt|openai|noreply@anthropic'

msg_file=""
history_only=0
rev="--all"
while (($#)); do
  case "$1" in
    --msg-file) msg_file="${2:-}"; shift 2 || shift ;;
    --history-only) history_only=1; shift ;;
    --rev) rev="${2:?--rev needs a revision}"; shift 2 ;;
    *) printf 'audit_identity.sh: unknown argument: %s\n' "$1" >&2; exit 2 ;;
  esac
done

cd "$(git rev-parse --show-toplevel)"

fail=0
err() { printf 'FAIL: %s\n' "$*" >&2; fail=1; }
ok() { printf 'ok:   %s\n' "$*"; }

# --- 1. Effective git identity ------------------------------------------------
if ((history_only)); then
  ok "git config identity skipped (--history-only)"
else
  name="$(git config user.name || true)"
  email="$(git config user.email || true)"
  [[ "$name" == "$EXPECTED_NAME" ]] && ok "user.name = $name" || err "user.name is '$name', expected '$EXPECTED_NAME'"
  [[ "$email" == "$EXPECTED_EMAIL" ]] && ok "user.email = $email" || err "user.email is '$email', expected '$EXPECTED_EMAIL'"
fi

# --- 2. Pending commit message (optional) -------------------------------------
audit_message() {
  local label="$1" body="$2"
  if grep -Eiq "$FORBIDDEN_RE" <<<"$body"; then
    err "$label contains forbidden attribution: $(grep -Ei "$FORBIDDEN_RE" <<<"$body" | head -1)"
  fi
  local trailers
  trailers="$(git interpret-trailers --parse <<<"$body")"
  [[ -z "$trailers" ]] || err "$label carries trailers: $trailers"
}

if [[ -n "$msg_file" ]]; then
  [[ -f "$msg_file" ]] || { err "--msg-file requires an existing file"; exit 1; }
  audit_message "pending message" "$(git stripspace --strip-comments <"$msg_file")"
  ok "pending message checked"
fi

# --- 3. Full history ----------------------------------------------------------
if git rev-parse --verify --quiet HEAD >/dev/null; then
  count=0
  while IFS= read -r sha; do
    count=$((count + 1))
    an="$(git show -s --format='%an' "$sha")"; ae="$(git show -s --format='%ae' "$sha")"
    cn="$(git show -s --format='%cn' "$sha")"; ce="$(git show -s --format='%ce' "$sha")"
    [[ "$an" == "$EXPECTED_NAME" && "$ae" == "$EXPECTED_EMAIL" ]] || err "$sha author is '$an <$ae>'"
    [[ "$cn" == "$EXPECTED_NAME" && "$ce" == "$EXPECTED_EMAIL" ]] || err "$sha committer is '$cn <$ce>'"
    audit_message "commit $sha" "$(git show -s --format='%B' "$sha")"
  done < <(git rev-list "$rev")
  ((count > 0)) || err "no commits reachable from $rev"
  ok "history checked ($count commits reachable from $rev)"
else
  ok "history empty (no commits yet)"
fi

if ((fail)); then
  printf '\naudit_identity: FAILED\n' >&2
  exit 1
fi
printf '\naudit_identity: PASSED\n'
